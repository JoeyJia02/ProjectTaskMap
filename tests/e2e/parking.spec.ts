import { test, expect } from '@playwright/test';

test('quick ideas persist relationships and edits across page reload', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('项目名称').fill('Parking browser check');
  await page.getByLabel('绑定 key').fill(`parking-browser-${Date.now()}`);
  await page.getByLabel('部署者凭据').fill('e2e-only-owner-secret-never-use-in-production');
  await page.getByRole('button', { name: /连接项目地图/ }).click();
  await expect(page.getByRole('button', { name: '＋ 添加任务' })).toBeVisible();
  await page.getByRole('button', { name: '＋ 添加任务' }).click();
  await page.getByLabel('任务名称').fill('登录页面');
  await page.getByRole('button', { name: '添加到地图' }).click();
  await page.getByRole('treeitem', { name: '登录页面，待开始' }).click();
  await page.getByRole('button', { name: '为此任务记想法' }).click();
  await expect(page.getByRole('checkbox', { name: '登录页面' })).toBeChecked();
  await page.getByLabel('一句话想法').fill('支持扫码登录');
  await page.getByLabel('补充说明（可选）').fill('先记下来，后续评估。');
  await page.getByLabel('想法优先级').selectOption('high');
  await page.getByRole('checkbox', { name: '置顶', exact: true }).check();
  await page.getByRole('button', { name: '存入 Parking Lot' }).click();
  await expect(page.locator('.idea-item')).toHaveCount(1);
  await expect(page.locator('.idea-item')).toContainText('支持扫码登录');
  await expect(page.locator('.idea-item')).toContainText('登录页面');
  await expect(page.locator('.idea-item')).toContainText('置顶 · 高优先级');
  await page.getByRole('button', { name: '编辑想法', exact: true }).click();
  await page.getByLabel('一句话想法').fill('评估扫码登录');
  await page.getByRole('button', { name: '保存想法', exact: true }).click();
  await expect(page.locator('.idea-item')).toContainText('评估扫码登录');
  await page.screenshot({ path: '.tmp/parking-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 430, height: 900 });
  await page.screenshot({ path: '.tmp/parking-narrow.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.reload();
  await page.getByLabel('项目名称').fill('Parking browser check');
  await page.getByLabel('部署者凭据').fill('e2e-only-owner-secret-never-use-in-production');
  await page.getByRole('button', { name: /连接项目地图/ }).click();
  await page.getByRole('button', { name: /^Parking Lot/ }).click();
  await expect(page.locator('.idea-item')).toContainText('评估扫码登录');
  await expect(page.locator('.idea-item')).toContainText('登录页面');
  await page.getByRole('button', { name: '↗ 登录页面' }).click();
  await expect(page.getByRole('dialog')).toContainText('评估扫码登录');
});
